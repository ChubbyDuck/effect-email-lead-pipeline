import { deploymentNamed, flociEndpointOf } from '@leads/shared/deployments';
import { resourceNames } from '@leads/shared/names';

import type { Case, Context, Destination } from './cases';

export type Entry = { readonly item: Case; readonly file: string; readonly key: string };

export type Settings = {
  readonly deployment: string;
  readonly seed: number;
  readonly rows: number;
  readonly skipLarge: boolean;
  readonly prefix: string;
  readonly context: Context;
};

type Folder = { readonly folder: string; readonly heading: string; readonly how: (settings: Settings) => string };

export const folders: Record<Destination, Folder> = {
  'email-attachment': {
    folder: '1-email-attachments',
    heading: 'Attachments for a real email',
    how: ({ context }) =>
      `Attach the file to an email from \`${context.owner}\` (Gmail web or app) to \`${context.recipient}\`. Attach one file per email, or many: each attachment is its own source. Each workbook here can also go direct to the lead-sources bucket (see section 3).`,
  },
  'inbox-bucket': {
    folder: '2-inbox-bucket',
    heading: 'Emails for the inbox bucket',
    how: ({ context }) =>
      `Put the file in \`${context.buckets.inbox}\`. This is the path of an email that SES received. Each email carries an \`Authentication-Results\` header in the form that SES writes, so these files can test the sender check, which a real email cannot (a real email always gets the true SES result).`,
  },
  'lead-sources-bucket': {
    folder: '3-lead-sources-bucket',
    heading: 'Workbooks for the lead-sources bucket',
    how: ({ context }) =>
      `Put the file in \`${context.buckets.leadSources}\`. This skips the email and the sender check.`,
  },
  'leads-queue': {
    folder: '4-leads-queue',
    heading: 'Messages for the leads queue',
    how: () => 'Send the file as the body of one message to the leads queue. This skips the email and the workbook.',
  },
  'inbox-queue': {
    folder: '5-inbox-queue',
    heading: 'S3 notifications for the inbox queue',
    how: () => 'Send the file as the body of one message to the inbox queue, as if S3 sent it.',
  },
  'lead-sources-queue': {
    folder: '6-lead-sources-queue',
    heading: 'S3 notifications for the lead-sources queue',
    how: () => 'Send the file as the body of one message to the lead-sources queue, as if S3 sent it.',
  },
};

const order: readonly Destination[] = [
  'email-attachment',
  'inbox-bucket',
  'lead-sources-bucket',
  'leads-queue',
  'inbox-queue',
  'lead-sources-queue',
];

const text = (value: string | ((context: Context) => string) | undefined, context: Context) =>
  typeof value === 'function' ? value(context) : (value ?? '');

/** The endpoint of the Floci of a deployment on this machine, such as `local-cdk`. A deployment in AWS has none. */
const flociEndpoint = (settings: Settings) => flociEndpointOf(deploymentNamed(settings.deployment));
const isOnFloci = (settings: Settings) => flociEndpoint(settings) !== undefined;

const awsFlags = (settings: Settings) => {
  const endpoint = flociEndpoint(settings);
  return endpoint === undefined
    ? `--region ${settings.context.region}`
    : `--endpoint-url ${endpoint} --region ${settings.context.region}`;
};

const queueNames: Partial<Record<Destination, (prefix: string) => string>> = {
  'leads-queue': (prefix) => resourceNames(prefix).queue('leads'),
  'inbox-queue': (prefix) => resourceNames(prefix).queue('inbox'),
  'lead-sources-queue': (prefix) => resourceNames(prefix).queue('leadSources'),
};

/** The shell command that sends one entry. Run it from `tools/generator`. An email attachment has no command. */
export function commandOf({ item, file, key }: Entry, settings: Settings): string | undefined {
  const flags = awsFlags(settings);
  const { buckets } = settings.context;
  switch (item.destination) {
    case 'email-attachment':
      return undefined;
    case 'inbox-bucket':
      return `aws s3 cp "output/catalog/${file}" "s3://${buckets.inbox}/${key}" ${flags}`;
    case 'lead-sources-bucket':
      return `aws s3 cp "output/catalog/${file}" "s3://${buckets.leadSources}/${key}" ${flags}`;
    default:
      return `aws sqs send-message --queue-url "$QUEUE" --message-body "file://output/catalog/${file}" ${flags}`;
  }
}

const cell = (value: string) => value.replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function readme(entries: readonly Entry[], settings: Settings): string {
  const { context } = settings;
  const flags = awsFlags(settings);
  const names = resourceNames(settings.prefix);
  const credentials = isOnFloci(settings) ? 'AWS_ACCESS_KEY_ID=test AWS_SECRET_ACCESS_KEY=test ' : '';
  const lines: string[] = [
    '# Test inputs of the leads pipeline',
    '',
    `Generated by \`pnpm catalog --deployment ${settings.deployment} --rows ${settings.rows} --seed ${settings.seed}${settings.skipLarge ? ' --skip-large' : ''}\`. This folder is git-ignored. The same command with the same seed makes the same leads again.`,
    '',
    `- Deployment: \`${settings.deployment}\` (prefix \`${settings.prefix}\`, Region \`${context.region}\`).`,
    `- A valid workbook has ${settings.rows} lead rows, unless its case says otherwise.`,
    `- Run every command from \`tools/generator\`.${credentials === '' ? '' : ` Put \`${credentials.trim()}\` in front of each command for Floci.`}`,
    '- A file name is `<case ID>--<what it is>.<extension>`. The case IDs are the IDs of the input catalog.',
    '- `manifest.json` has the same data for scripts.',
    '',
    '## Outcome codes',
    '',
    '| Code | What you see |',
    '| --- | --- |',
    '| **OK(n)** | `n` new items in the orders table. The email is deleted from the inbox bucket, and each workbook is deleted from the lead-sources bucket. All DLQs stay empty. Orders appear about 30 s after the workbook. |',
    '| **NO-SOURCES** | The email is deleted from the inbox bucket. Nothing else happens. |',
    '| **REJECTED** | The email is deleted from the inbox bucket, with an error log. No sources and no DLQ message. |',
    '| **INBOX-DLQ** | The email stays in the inbox bucket. One message goes to the inbox DLQ. |',
    '| **SRC-DELETED** | The workbook is deleted from the lead-sources bucket, with an error log. No leads and no DLQ message. |',
    '| **SRC-DLQ** | The workbook stays in the lead-sources bucket. One message goes to the lead-sources DLQ. |',
    '| **LEADS-DLQ** | The message goes to the leads DLQ. The other messages of its batch are acknowledged. |',
    '',
    `Each email that reaches the inbox handler also gets a \`pending\` entry in \`${names.requestLedgerTable}\`.`,
    '',
    '## Where to look',
    '',
    '| What | Where |',
    '| --- | --- |',
    `| Orders | DynamoDB \`${names.ordersTable}\` |`,
    `| Request ledger | DynamoDB \`${names.requestLedgerTable}\` |`,
    `| Dead letters | SQS \`${names.dlq('inbox')}\`, \`${names.dlq('leadSources')}\`, \`${names.dlq('leads')}\` |`,
    '| Reasons | CloudWatch Logs of the three handlers. A DLQ message does not carry the reason. |',
    `| All of it | \`DEPLOYMENT=${settings.deployment} pnpm lab${isOnFloci(settings) ? ':local' : ''}\` |`,
    '',
  ];

  order.forEach((destination, index) => {
    const section = entries.filter((entry) => entry.item.destination === destination);
    if (section.length === 0) return;
    const { folder, heading, how } = folders[destination];
    lines.push(`## ${index + 1}. ${heading} — \`${folder}/\``, '', how(settings), '');
    lines.push('| Case | File | What it is | Expected |', '| --- | --- | --- | --- |');
    for (const { item, file } of section) {
      const note = text(item.note, context);
      const what = `${item.title}${item.large ? ' (large)' : ''}${note === '' ? '' : `. _${note}_`}`;
      lines.push(
        `| ${item.id} | \`${file.slice(folder.length + 1)}\` | ${cell(what)} | ${cell(text(item.expected, context))} |`
      );
    }
    lines.push('');

    if (destination === 'email-attachment') {
      lines.push(
        'Recipes for a real email:',
        '',
        '- **No attachment** → NO-SOURCES.',
        '- **A5-01, A5-02, and A5-03 in one email** → one OK per workbook.',
        '- **The same email two times** → the second one makes no new order.',
        '- **A7-03a, then A7-03b** in two emails → one new order for the changed row.',
        '- **A forged sender** needs a different mail server. Use the A2 files in section 2. They carry the result that SES writes for such an email.',
        ''
      );
      return;
    }

    const queueName = queueNames[destination];
    lines.push('```sh');
    if (queueName !== undefined) {
      lines.push(
        `QUEUE=$(${credentials}aws sqs get-queue-url --queue-name ${queueName(settings.prefix)} --query QueueUrl --output text ${flags})`
      );
    }
    for (const entry of section) lines.push(`${credentials}${commandOf(entry, settings)}   # ${entry.item.id}`);
    lines.push('```', '');
  });

  lines.push(
    '## Not in this folder',
    '',
    'These cases of the catalog need no file, or a file cannot make them:',
    '',
    '- An email to a different address on the domain: SES does not take it in.',
    '- An email over 40 MB: SES bounces it. Gmail also refuses attachments over 25 MB.',
    '- A password-protected `.xlsx`: SheetJS cannot write one. It is a CFB container, as `A4-03` is, so the result is the same.',
    '- A leads message without a message ID, or with an empty body: SQS never delivers one.',
    '- A duplicate S3 notification after a successful run: send the `E1-06` form with the key of an email that is already deleted.',
    ''
  );
  return lines.join('\n');
}

export function manifest(entries: readonly Entry[], settings: Settings) {
  return {
    deployment: settings.deployment,
    seed: settings.seed,
    rows: settings.rows,
    skipLarge: settings.skipLarge,
    cases: entries.map((entry) => ({
      id: entry.item.id,
      file: entry.file,
      destination: entry.item.destination,
      title: entry.item.title,
      expected: text(entry.item.expected, settings.context),
      ...(entry.item.note === undefined ? {} : { note: text(entry.item.note, settings.context) }),
      ...(entry.item.large ? { large: true } : {}),
      ...(entry.item.destination === 'inbox-bucket' || entry.item.destination === 'lead-sources-bucket'
        ? { key: entry.key }
        : {}),
      ...(queueNames[entry.item.destination] === undefined
        ? {}
        : { queue: queueNames[entry.item.destination]!(settings.prefix) }),
      ...(commandOf(entry, settings) === undefined ? {} : { command: commandOf(entry, settings) }),
    })),
  };
}
